#!/usr/bin/env node
/**
 * Generates app/src/styles/theme.generated.css from Daintree's own theme engine, so Decisions wears exactly the
 * Daintree (dark) and Bondi (light) themes and cannot drift from them by hand.
 *
 *   DAINTREE_DIR=/path/to/daintree pnpm --filter @daintreehq/decisions-app theme
 *
 * DAINTREE_DIR defaults to a `daintree` checkout beside this repository. The output is committed, so building
 * Decisions never needs Daintree; rerun this when Daintree's themes change.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const daintree = resolve(process.env.DAINTREE_DIR ?? join(repo, '..', 'daintree'));
const themes = join(daintree, 'shared/theme/themes.ts');
const tsx = join(daintree, 'node_modules/.bin/tsx');
if (!existsSync(themes) || !existsSync(tsx)) {
  console.error(
    `No Daintree checkout with installed dependencies at ${daintree}. Set DAINTREE_DIR.`,
  );
  process.exit(1);
}

const tmp = mkdtempSync(join(tmpdir(), 'decisions-theme-'));
const probe = join(tmp, 'dump.ts');
writeFileSync(
  probe,
  `import { getAppThemeById, getAppThemeCssVariables } from ${JSON.stringify(themes)};
const out: Record<string, Record<string, string>> = {};
for (const id of ['daintree', 'bondi']) out[id] = getAppThemeCssVariables(getAppThemeById(id)!);
process.stdout.write(JSON.stringify(out));
`,
);
let vars;
try {
  vars = JSON.parse(execFileSync(tsx, [probe], { cwd: daintree, encoding: 'utf8' }));
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const commit = (() => {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: daintree,
      encoding: 'utf8',
    }).trim();
  } catch {
    return 'unknown';
  }
})();

/** Only the shared semantic tokens and the grain tile; Daintree's IDE-specific extensions stay behind. */
const ideOnly =
  /^--theme-(terminal|diff|pr|search|panel-state|category|knob|state-modified)|^--theme-syntax-(?!keyword)/;
const keep = (k) =>
  (k.startsWith('--theme-') && !ideOnly.test(k)) ||
  k === '--grain-image' ||
  k.startsWith('--sidebar-');

function block(selector, id, scheme) {
  const entries = Object.entries(vars[id])
    .filter(([k]) => keep(k))
    .sort(([a], [b]) => a.localeCompare(b));
  return `${selector} {\n  color-scheme: ${scheme};\n${entries.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
}

const css = `/* Generated by app/scripts/sync-theme.mjs from Daintree ${commit}. Do not edit by hand. */

/* Daintree (dark) is the default; Bondi (light) applies when chosen, or when the device prefers light. */
${block(":root,\n:root[data-theme='daintree']", 'daintree', 'dark')}
${block(":root[data-theme='bondi']", 'bondi', 'light')}
@media (prefers-color-scheme: light) {
${block(':root:not([data-theme])', 'bondi', 'light')
  .split('\n')
  .map((l) => (l ? '  ' + l : l))
  .join('\n')}}
`;

const out = join(repo, 'app/src/styles/theme.generated.css');
writeFileSync(out, css);
console.log(`Wrote ${out} from Daintree ${commit}.`);
